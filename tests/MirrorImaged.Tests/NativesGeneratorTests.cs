using System.Text;
using MirrorImaged.NativesGenerator;

namespace MirrorImaged.Tests;

public sealed class NativesGeneratorTests : IDisposable
{
    const string CommonJ = """
        // A comment
        type agent extends handle
        type event extends agent // an event
        type unit extends agent

        globals
            constant integer BASE = 2
        endglobals

        native GetTriggerUnit takes nothing returns unit
        constant native GetUnitX takes unit whichUnit returns real
        native   SetUnitName   takes unit whichUnit, string name, integer base returns nothing
        native TriggerRegisterEvent takes event e, code callback, boolean once returns handle
        native Condition takes code func returns boolean

        function Helper takes nothing returns nothing
        endfunction
        """;

    const string CommonAi = """
        native SetHeroLevels takes code func returns nothing
        native AiDebug takes string text returns nothing
        """;

    readonly string _folder = Directory.CreateDirectory(Path.Combine(Path.GetTempPath(), Path.GetRandomFileName())).FullName;

    public void Dispose() => Directory.Delete(_folder, true);

    [Fact]
    public void Reads_the_handle_types_and_their_parents()
    {
        var script = Generator.Read(CommonJ);

        Assert.Equal([new("agent", "handle"), new("event", "agent"), new("unit", "agent")], script.Types);
    }

    [Fact]
    public void Reads_the_natives_with_their_parameters_and_returns_and_leaves_out_functions()
    {
        var script = Generator.Read(CommonJ);

        Assert.Equal(
            ["GetTriggerUnit", "GetUnitX", "SetUnitName", "TriggerRegisterEvent", "Condition"],
            script.Natives.Select(native => native.Name));
        Assert.Empty(script.Natives[0].Parameters);
        Assert.Equal("unit", script.Natives[0].Returns);
        Assert.Equal([new("unit", "whichUnit"), new("string", "name"), new("integer", "base")], script.Natives[2].Parameters);
        Assert.Equal("nothing", script.Natives[2].Returns);
        Assert.Equal("handle", script.Natives[3].Returns);
    }

    [Fact]
    public void A_script_that_is_not_jass_is_an_error()
    {
        Assert.ThrowsAny<Exception>(() => Generator.Read("native Broken takes returns"));
    }

    [Fact]
    public void Writes_a_class_per_handle_type_sorted_with_handle_first()
    {
        var types = Generate()["Types.g.cs"];

        Assert.Equal("""
            // Generated by MirrorImaged.NativesGenerator from common.j and common.ai, game 1.2.3. Do not edit.

            #pragma warning disable CS8981 // The types keep common.j's names, which are lower case.

            namespace MirrorImaged.Natives;

            public class handle;
            public class agent : handle;
            public class @event : agent;
            public class unit : agent;

            """.ReplaceLineEndings("\n"), types);
    }

    [Fact]
    public void Writes_a_missing_stub_per_native_sorted_with_its_typed_signature()
    {
        var natives = Generate()["CommonJNatives.g.cs"];

        Assert.Equal("""
            // Generated by MirrorImaged.NativesGenerator from common.j, game 1.2.3. Do not edit.

            #nullable enable

            namespace MirrorImaged.Natives;

            public sealed partial class GameNatives
            {
                [Native(Level.Missing)]
                public bool Condition(Func<bool>? func) => throw new MissingNativeException("Condition");

                [Native(Level.Missing)]
                public unit? GetTriggerUnit() => throw new MissingNativeException("GetTriggerUnit");

                [Native(Level.Missing)]
                public float GetUnitX(unit? whichUnit) => throw new MissingNativeException("GetUnitX");

                [Native(Level.Missing)]
                public void SetUnitName(unit? whichUnit, string? name, int @base) => throw new MissingNativeException("SetUnitName");

                [Native(Level.Missing)]
                public handle? TriggerRegisterEvent(@event? e, Action? callback, bool once) => throw new MissingNativeException("TriggerRegisterEvent");
            }

            """.ReplaceLineEndings("\n"), natives);
    }

    [Fact]
    public void Writes_common_ai_s_natives_to_their_own_file()
    {
        var natives = Generate()["CommonAiNatives.g.cs"];

        Assert.StartsWith("// Generated by MirrorImaged.NativesGenerator from common.ai, game 1.2.3. Do not edit.\n", natives);
        Assert.Contains("public void AiDebug(string? text) => throw new MissingNativeException(\"AiDebug\");", natives);
        Assert.Contains("public void SetHeroLevels(Func<int>? func)", natives);
    }

    [Fact]
    public void Leaves_out_the_natives_written_by_hand()
    {
        var natives = Generate(new HashSet<string> { "GetUnitX", "AiDebug" });

        Assert.DoesNotContain("GetUnitX", natives["CommonJNatives.g.cs"]);
        Assert.Contains("GetTriggerUnit", natives["CommonJNatives.g.cs"]);
        Assert.DoesNotContain("AiDebug", natives["CommonAiNatives.g.cs"]);
    }

    [Fact]
    public void The_same_scripts_give_the_same_files()
    {
        Assert.Equal(Generate(), Generate());
    }

    [Fact]
    public void A_script_missing_from_the_install_is_an_error_that_names_it()
    {
        var error = Assert.Throws<FileNotFoundException>(() =>
            Generator.Generate(path => path.EndsWith("common.j") ? Encoding.UTF8.GetBytes(CommonJ) : null, "1.2.3", new HashSet<string>()));

        Assert.Contains("common.ai", error.Message);
    }

    [Fact]
    public void The_natives_written_by_hand_are_the_methods_outside_generated_bin_and_obj()
    {
        Write("Timers.cs", """
            partial class GameNatives
            {
                [Native(Level.Exact, Fact = "Timers")]
                public void TimerStart(timer? whichTimer, float timeout, bool periodic, Action? handlerFunc) { }

                public   int  GetPlayerId (player? whichPlayer) => 0;

                public @event? TriggerRegisterTimerEvent(trigger? whichTrigger, float timeout, bool periodic) => null;

                public static Func<bool>? Condition(Func<bool>? func) => func;

                public GameNatives(World world) { }

                void Helper() { }
            }
            """);
        Write("Units/Positions.cs", "public float GetUnitX(unit? whichUnit) => 0;");
        Write("Generated/CommonJNatives.g.cs", "public void Generated() => throw null;");
        Write("obj/Debug/Some.cs", "public void Built() { }");
        Write("bin/Some.cs", "public void Copied() { }");

        Assert.Equal(
            ["Condition", "GetPlayerId", "GetUnitX", "TimerStart", "TriggerRegisterTimerEvent"],
            Generator.HandWritten(_folder).Order(StringComparer.Ordinal));
    }

    static IReadOnlyDictionary<string, string> Generate(IReadOnlySet<string>? handWritten = null) =>
        Generator.Generate(
            path => Encoding.UTF8.GetBytes(path.EndsWith("common.j") ? CommonJ : CommonAi),
            "1.2.3",
            handWritten ?? new HashSet<string>());

    void Write(string path, string text)
    {
        var full = Path.Combine(_folder, path);
        Directory.CreateDirectory(Path.GetDirectoryName(full)!);
        File.WriteAllText(full, text);
    }
}

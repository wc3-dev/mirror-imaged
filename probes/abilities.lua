-- Abilities on units without casting (W2-7), on the probe map (custom_v1's data): adding and removing, levels and
-- their edges, the ability handles and their order on a unit, hiding, disabling and permanence, an ability the player
-- may not use, Avul and SetUnitInvulnerable, and an upgrade that raises an ability's level.
local function show(v) return v == nil and "nil" or tostring(v) end
local function kind(h) return h == nil and "nil" or tostring(h):match("^[%a_]+") end
local function name(id) return id == 0 and "0" or string.pack(">I4", id) end
local spot = 0
local function make(id, p)
  spot = spot % 225 + 1
  return CreateUnit(p or Player(0), FourCC(id), (spot % 15) * 200 - 1400, (spot // 15) * 200 - 1400, 0)
end
local function part(at, label, f)
  TimerStart(CreateTimer(), at, false, function()
    out(label)
    local ok, err = pcall(f)
    if not ok then out(label .. " error " .. tostring(err)) end
  end)
end
local function lv(u, id) return GetUnitAbilityLevel(u, FourCC(id)) end
local function list(u)
  local ids = {}
  for i = 0, 15 do
    local a = BlzGetUnitAbilityByIndex(u, i)
    if a == nil then break end
    ids[#ids + 1] = name(BlzGetAbilityId(a))
  end
  return table.concat(ids, ",") .. " " .. show(BlzGetUnitAbilityByIndex(u, -1))
end

TimerStart(CreateTimer(), 4.0, false, guard(function() done() end))


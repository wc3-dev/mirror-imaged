part(0.1, "levels", function()
  local u = make("hfoo")
  local hb = FourCC("AHhb")
  out("set lacking " .. SetUnitAbilityLevel(u, hb, 2) .. " " .. lv(u, "AHhb") .. " inc " .. IncUnitAbilityLevel(u, hb) .. " " .. lv(u, "AHhb")
    .. " dec " .. DecUnitAbilityLevel(u, hb) .. " " .. lv(u, "AHhb"))
  UnitAddAbility(u, hb)
  for _, n in ipairs({ 2, 4, 100, 0, -1, 3, 1 }) do
    out("set " .. n .. " " .. SetUnitAbilityLevel(u, hb, n) .. " " .. lv(u, "AHhb"))
  end
  out("dec at 1 " .. DecUnitAbilityLevel(u, hb) .. " " .. lv(u, "AHhb"))
  for _ = 1, 4 do out("inc " .. IncUnitAbilityLevel(u, hb) .. " " .. lv(u, "AHhb")) end
  out("set at 5 to 2 " .. SetUnitAbilityLevel(u, hb, 2) .. " " .. lv(u, "AHhb"))
  out("set at 2 to 5 " .. SetUnitAbilityLevel(u, hb, 5) .. " " .. lv(u, "AHhb"))
  for _ = 1, 2 do out("dec " .. DecUnitAbilityLevel(u, hb) .. " " .. lv(u, "AHhb")) end
  out("defend set 2 " .. SetUnitAbilityLevel(u, FourCC("Adef"), 2) .. " " .. lv(u, "Adef") .. " inc " .. IncUnitAbilityLevel(u, FourCC("Adef")) .. " " .. lv(u, "Adef"))
  out("remove " .. show(UnitRemoveAbility(u, hb)) .. " " .. lv(u, "AHhb") .. " again " .. show(UnitRemoveAbility(u, hb)))
  out("add after inc " .. show(UnitAddAbility(u, hb)) .. " " .. lv(u, "AHhb"))
  out("remove own " .. show(UnitRemoveAbility(u, FourCC("Adef"))) .. " " .. lv(u, "Adef") .. " add back " .. show(UnitAddAbility(u, FourCC("Adef"))) .. " " .. lv(u, "Adef"))
  out("remove Aatk " .. show(UnitRemoveAbility(u, FourCC("Aatk"))) .. " " .. lv(u, "Aatk") .. " Amov " .. show(UnitRemoveAbility(u, FourCC("Amov"))) .. " " .. lv(u, "Amov"))
  out("nil " .. SetUnitAbilityLevel(nil, hb, 2) .. " " .. IncUnitAbilityLevel(nil, hb) .. " " .. DecUnitAbilityLevel(nil, hb) .. " " .. show(UnitRemoveAbility(nil, hb)))
end)

part(0.15, "handles", function()
  local u = make("hfoo")
  local before = CreateTimer()
  local a = BlzGetUnitAbility(u, FourCC("Adef"))
  local between = CreateTimer()
  local b = BlzGetUnitAbility(u, FourCC("Adef"))
  local after = CreateTimer()
  out("ids " .. (GetHandleId(a) - GetHandleId(before)) .. " " .. (GetHandleId(between) - GetHandleId(a)) .. " " .. (GetHandleId(b) - GetHandleId(a))
    .. " " .. (GetHandleId(after) - GetHandleId(between)) .. " " .. kind(a) .. " eq " .. show(a == b) .. " " .. show(rawequal(a, b)))
  out("id " .. name(BlzGetAbilityId(a)) .. " nil " .. BlzGetAbilityId(nil) .. " lacking " .. show(BlzGetUnitAbility(u, FourCC("AHhb"))) .. " " .. show(BlzGetUnitAbility(nil, FourCC("Adef"))))
  local i0 = BlzGetUnitAbilityByIndex(u, 0)
  out("index " .. kind(i0) .. " " .. (GetHandleId(i0) - GetHandleId(a)))
  for _, id in ipairs({ "hfoo", "hpea", "Hpal", "hbar", "hgry", "nshe", "hkni", "Hamg" }) do out(id .. " " .. list(make(id))) end
  UnitAddAbility(u, FourCC("AHhb"))
  UnitAddAbility(u, FourCC("AHtb"))
  out("added " .. list(u))
  UnitRemoveAbility(u, FourCC("Adef"))
  out("removed " .. list(u))
  UnitAddAbility(u, FourCC("Adef"))
  out("added back " .. list(u))
  local c = BlzGetUnitAbility(u, FourCC("Adef"))
  out("new handle " .. (GetHandleId(c) - GetHandleId(a)) .. " old id " .. name(BlzGetAbilityId(a)) .. " eq " .. show(a == c))
  local hb = BlzGetUnitAbility(u, FourCC("AHhb"))
  UnitRemoveAbility(u, FourCC("AHhb"))
  out("removed handle " .. show(BlzGetAbilityId(hb)) .. " " .. kind(hb))
  local g = make("hfoo")
  local ga = BlzGetUnitAbility(g, FourCC("Adef"))
  RemoveUnit(g)
  out("unit removed " .. name(BlzGetAbilityId(ga)))
  TimerStart(CreateTimer(), 0, false, function() out("unit gone " .. show(BlzGetAbilityId(ga)) .. " " .. kind(ga)) end)
end)

part(0.2, "hide", function()
  local u = make("hfoo")
  local df = FourCC("Adef")
  BlzUnitHideAbility(u, df, true)
  out("hidden " .. lv(u, "Adef") .. " " .. kind(BlzGetUnitAbility(u, df)) .. " " .. list(u))
  BlzUnitHideAbility(u, df, false)
  BlzUnitDisableAbility(u, df, true, true)
  out("disabled " .. lv(u, "Adef") .. " " .. kind(BlzGetUnitAbility(u, df)) .. " " .. list(u))
  BlzUnitDisableAbility(u, df, false, false)
  BlzUnitHideAbility(u, FourCC("AHhb"), true)
  BlzUnitDisableAbility(u, FourCC("AHtb"), true, true)
  out("lacking " .. lv(u, "AHhb") .. " " .. lv(u, "AHtb") .. " add " .. show(UnitAddAbility(u, FourCC("AHhb"))) .. " " .. show(UnitAddAbility(u, FourCC("AHtb"))))
  out("permanent " .. show(UnitMakeAbilityPermanent(u, true, df)) .. " " .. show(UnitMakeAbilityPermanent(u, true, df)) .. " " .. show(UnitMakeAbilityPermanent(u, false, df))
    .. " lacking " .. show(UnitMakeAbilityPermanent(u, true, FourCC("AHds"))) .. " " .. lv(u, "AHds") .. " " .. show(UnitMakeAbilityPermanent(u, false, FourCC("AHds")))
    .. " unknown " .. show(UnitMakeAbilityPermanent(u, true, FourCC("zzzz"))) .. " nil " .. show(UnitMakeAbilityPermanent(nil, true, df)))
  UnitMakeAbilityPermanent(u, true, df)
  out("permanent removed " .. show(UnitRemoveAbility(u, df)) .. " " .. lv(u, "Adef"))
end)

part(0.25, "available", function()
  local u = make("hfoo")
  local df = FourCC("Adef")
  SetPlayerAbilityAvailable(Player(0), df, false)
  local v = make("hfoo")
  out("unavailable " .. lv(u, "Adef") .. " " .. kind(BlzGetUnitAbility(u, df)) .. " new " .. lv(v, "Adef") .. " " .. list(v))
  SetPlayerAbilityAvailable(Player(0), FourCC("AHtb"), false)
  out("add unavailable " .. show(UnitAddAbility(u, FourCC("AHtb"))) .. " " .. lv(u, "AHtb") .. " set " .. SetUnitAbilityLevel(u, FourCC("AHtb"), 2))
  local w = make("hfoo", Player(1))
  out("other player " .. lv(w, "Adef"))
  SetPlayerAbilityAvailable(Player(0), df, true)
  SetPlayerAbilityAvailable(Player(0), FourCC("AHtb"), true)
  out("available " .. lv(u, "Adef") .. " " .. lv(v, "Adef") .. " " .. lv(u, "AHtb"))
end)

part(0.3, "invulnerable", function()
  local u = make("hfoo")
  local vul = FourCC("Avul")
  SetUnitInvulnerable(u, true)
  out("set " .. lv(u, "Avul") .. " " .. kind(BlzGetUnitAbility(u, vul)) .. " " .. show(BlzIsUnitInvulnerable(u)) .. " " .. list(u))
  out("remove " .. show(UnitRemoveAbility(u, vul)) .. " " .. lv(u, "Avul") .. " " .. show(BlzIsUnitInvulnerable(u)))
  SetUnitInvulnerable(u, true)
  SetUnitInvulnerable(u, false)
  out("unset " .. lv(u, "Avul") .. " " .. show(BlzIsUnitInvulnerable(u)))
  out("add " .. show(UnitAddAbility(u, vul)) .. " " .. lv(u, "Avul") .. " " .. show(BlzIsUnitInvulnerable(u)))
  SetUnitInvulnerable(u, false)
  out("unset added " .. lv(u, "Avul") .. " " .. show(BlzIsUnitInvulnerable(u)))
  SetUnitInvulnerable(u, true)
  out("set added " .. lv(u, "Avul") .. " " .. show(BlzIsUnitInvulnerable(u)) .. " level " .. SetUnitAbilityLevel(u, vul, 2))
  out("remove added " .. show(UnitRemoveAbility(u, vul)) .. " " .. lv(u, "Avul") .. " " .. show(BlzIsUnitInvulnerable(u)))
end)

part(0.35, "upgrades", function()
  local p = Player(0)
  local e = make("hpea")
  local n = make("unec")
  local t = make("otau")
  local f = make("hfoo")
  out("before " .. lv(e, "Ahlh") .. " " .. lv(n, "Arai") .. " " .. lv(t, "Awar") .. " add " .. show(UnitAddAbility(f, FourCC("Ahlh"))) .. " " .. lv(f, "Ahlh"))
  SetPlayerTechResearched(p, FourCC("Rhlh"), 1)
  SetPlayerTechResearched(p, FourCC("Rusm"), 1)
  SetPlayerTechResearched(p, FourCC("Rows"), 1)
  local e2 = make("hpea")
  out("researched " .. lv(e, "Ahlh") .. " " .. lv(e2, "Ahlh") .. " " .. lv(n, "Arai") .. " " .. lv(t, "Awar") .. " " .. lv(f, "Ahlh"))
  local f2 = make("hfoo")
  out("added after " .. show(UnitAddAbility(f2, FourCC("Ahlh"))) .. " " .. lv(f2, "Ahlh") .. " other player " .. lv(make("hpea", Player(1)), "Ahlh"))
  SetPlayerTechResearched(p, FourCC("Rhlh"), 2)
  out("level 2 " .. lv(e, "Ahlh") .. " " .. lv(e2, "Ahlh") .. " " .. lv(f, "Ahlh") .. " " .. lv(f2, "Ahlh"))
  out("set " .. SetUnitAbilityLevel(e, FourCC("Ahlh"), 1) .. " " .. lv(e, "Ahlh") .. " inc " .. IncUnitAbilityLevel(e2, FourCC("Ahlh")) .. " " .. lv(e2, "Ahlh"))
  SetPlayerTechResearched(p, FourCC("Rhlh"), 0)
  out("unresearched " .. lv(e, "Ahlh") .. " " .. lv(e2, "Ahlh") .. " " .. lv(f, "Ahlh") .. " " .. lv(f2, "Ahlh") .. " new " .. lv(make("hpea"), "Ahlh"))
  local g = make("hfoo")
  SetPlayerTechResearched(p, FourCC("Rhlh"), 1)
  UnitAddAbility(g, FourCC("Ahlh"))
  SetUnitOwner(g, Player(1), true)
  out("given away " .. lv(g, "Ahlh"))
  SetUnitOwner(e2, Player(1), true)
  out("given away own " .. lv(e2, "Ahlh"))
  SetPlayerTechResearched(p, FourCC("Rhde"), 1)
  out("defend researched " .. lv(f, "Adef"))
end)

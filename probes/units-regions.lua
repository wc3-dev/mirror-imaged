-- Regions (W2-6), on the probe map (custom_v1's data): the 32 cells adding and clearing set, the point, location and
-- unit tests, and the enter and leave events: what fires them (CreateUnit, SetUnitX, SetUnitY, SetUnitPosition) and
-- what doesn't, when they fire against the code that moved the unit and a 0 s timer, their order over two regions,
-- their filters and the responses inside, and whether a region keeps who is inside or reads places (a cell cleared or
-- added under a unit standing still, then moved within it).
local function L(u) return u == nil and "nil" or tostring(GetUnitUserData(u)) end
local function make(n, id, x, y)
  local u = CreateUnit(Player(0), FourCC(id), x, y, 0)
  SetUnitUserData(u, n)
  return u
end
local function s(v) return v and "1" or "0" end
local function part(time, label, f)
  TimerStart(CreateTimer(), time, false, function()
    out(label)
    local ok, err = pcall(f)
    if not ok then out(label .. " error " .. tostring(err)) end
  end)
end

TimerStart(CreateTimer(), 3, false, guard(function() done() end))


-- The events, a line each as they come: the event (enter or leave) and its region, the unit and where it is as the
-- event fires, and the responses; the steps' marks between them.
local function note(text) out("> " .. text) end
local function flush(label) out("-- " .. label) end
local function watch(name, r, enter, filter)
  local t = CreateTrigger()
  if enter then TriggerRegisterEnterRegion(t, r, filter) else TriggerRegisterLeaveRegion(t, r, filter) end
  TriggerAddAction(t, function()
    local u = GetTriggerUnit()
    note((enter and "enter " or "leave ") .. name .. " " .. L(u) .. " at " .. math.floor(GetUnitX(u)) .. "," .. math.floor(GetUnitY(u))
      .. " " .. L(GetEnteringUnit()) .. "/" .. L(GetLeavingUnit()) .. "/" .. L(GetFilterUnit()) .. " event " .. GetHandleId(GetTriggerEventId())
      .. " region " .. tostring(GetTriggeringRegion() == r) .. " player " .. (GetTriggerPlayer() and GetPlayerId(GetTriggerPlayer()) or "nil")
      .. " type " .. (GetUnitTypeId(u) ~= 0 and "1" or "0"))
  end)
  return t
end

part(0.1, "events", function()
  local A, B = CreateRegion(), CreateRegion()
  RegionAddRect(A, Rect(1000, 1000, 1200, 1200))
  RegionAddRect(B, Rect(1100, 1000, 1300, 1200))
  -- B's triggers are registered first, so two regions entered at once fire B's first (game-facts)
  watch("B", B, true)
  watch("B", B, false)
  watch("A", A, true)
  watch("A", A, false)
  local u = make(2, "hfoo", 1050, 1050)
  note("made")
  TimerStart(CreateTimer(), 0, false, function() note("timer") end)
  local v = make(3, "hfoo", 500, 500)
  SetUnitX(v, 1150)
  note("x")
  SetUnitY(v, 1100)
  note("y")
  SetUnitX(v, 1500)
  note("out")
  local w = make(4, "hfoo", 1150, 1100)
  RemoveUnit(w)
  note("removed")
  TimerStart(CreateTimer(), 0.01, false, function()
    flush("create and move")
    SetUnitX(u, 1060)
    note("within")
    SetUnitPosition(u, 1050, 700)
    note("position out")
    SetUnitPosition(u, 1050, 1050)
    note("position in")
    KillUnit(u)
    note("killed")
    SetUnitX(u, 500)
    note("dead out")
    SetUnitX(u, 1050)
    note("dead in")
    ShowUnit(v, false)
    SetUnitX(v, 1150)
    note("hidden in")
    ShowUnit(v, true)
    RemoveUnit(v)
    note("removed inside")
    TimerStart(CreateTimer(), 0.01, false, function()
      flush("moves")
      local x = make(5, "hfoo", 1050, 1150)
      local y = make(6, "hfoo", 500, 1150)
      TimerStart(CreateTimer(), 0.01, false, function()
        flush("made inside")
        RegionClearRect(A, Rect(1000, 1100, 1090, 1200))
        out("cleared under " .. s(IsUnitInRegion(A, x)))
        SetUnitX(x, 1040)
        note("moved in cleared")
        RegionAddRect(A, Rect(400, 1100, 600, 1200))
        out("added under " .. s(IsUnitInRegion(A, y)))
        SetUnitX(y, 510)
        note("moved in added")
        SetUnitX(y, 700)
        note("moved out of added")
        RegionAddRect(A, Rect(1000, 1100, 1090, 1200))
        SetUnitX(x, 1500)
        note("x out")
        TimerStart(CreateTimer(), 0.01, false, function()
          flush("changed regions")
          local C = CreateRegion()
          RegionAddRect(C, Rect(-1200, 1000, -1000, 1200))
          local calls = {}
          local t = watch("C", C, true, Filter(function()
            calls[#calls + 1] = L(GetFilterUnit()) .. "/" .. L(GetTriggerUnit()) .. "/" .. L(GetEnteringUnit()) .. "/" .. GetHandleId(GetTriggerEventId())
            return GetUnitUserData(GetFilterUnit()) ~= 7
          end))
          TriggerRegisterEnterRegion(t, C, nil)
          local z1, z2 = make(7, "hfoo", -1100, 1100), make(8, "hfoo", -1100, 1150)
          local gone = make(9, "hfoo", 0, 0)
          local d = watch("D", C, true)
          SetUnitX(gone, -1050)
          DestroyTrigger(d)
          RemoveRegion(B)
          SetUnitY(z2, 900)
          TimerStart(CreateTimer(), 0.01, false, function()
            flush("filters")
            out("filter calls " .. table.concat(calls, ","))
            SetUnitX(gone, 1150)
            SetUnitY(gone, 1100)
            note("into removed B")
            TimerStart(CreateTimer(), 0.01, false, function()
              flush("removed region")
            end)
          end)
        end)
      end)
    end)
  end)
end)

-- The camera, fifth part (named units- for its footman's data): what ends the rotate mode, after its sweep and during
-- it; what a pan's height does on a reset, a follow and a stop; and the natives the first probes left as only shown:
-- the focal distance and depth of field scale, the smoothing factor, a camera blocker and a cinematic camera. Each step
-- runs after the wait before it.
local function F(x) return string.format("%.4f", x) end
local function target() return F(GetCameraTargetPositionX()) .. " " .. F(GetCameraTargetPositionY()) .. " " .. F(GetCameraTargetPositionZ()) end
local function eye() return F(GetCameraEyePositionX()) .. " " .. F(GetCameraEyePositionY()) .. " " .. F(GetCameraEyePositionZ()) end
local function field(i) return F(GetCameraField(ConvertCameraField(i))) end
local function fields()
  local t = {}
  for i = 0, 13 do t[#t + 1] = field(i) end
  return table.concat(t, " ")
end

local steps, blocker, reads = {}, nil, {}
local function step(wait, f) steps[#steps + 1] = {wait, f} end
local function run(i)
  if i > #steps then done() return end
  TimerStart(CreateTimer(), steps[i][1], false, guard(function() steps[i][2]() run(i + 1) end))
end
local function fresh()
  ResetToGameCamera(0)
  SetCameraPosition(0, 0)
end

SetCameraBounds(-2000, -2000, 2000, 2000, -2000, 2000, 2000, -2000)
local u = CreateUnit(Player(0), FourCC("hfoo"), -600, -600, 0)
step(0.5, function() SetCameraRotateMode(500, 0, math.pi / 2, 1) end)
step(1.5, function()
  out("rotated " .. target())
  SetCameraPosition(-300, 200)
end)
step(0.5, function()
  out("position after the sweep " .. target())
  fresh()
end)
step(0.5, function() SetCameraRotateMode(500, 0, math.pi / 2, 1) end)
step(0.5, function()
  out("half swept " .. target())
  SetCameraPosition(-300, 200)
end)
step(0.5, function() out("position during the sweep 0.5s " .. target()) end)
step(1, function()
  out("position during the sweep 1.5s " .. target())
  fresh()
end)
step(0.5, function() SetCameraRotateMode(500, 0, math.pi / 2, 1) end)
step(1.5, function()
  local a = CreateCameraSetup()
  CameraSetupSetDestPosition(a, -400, -300, 0)
  CameraSetupApply(a, true, true)
end)
step(0.5, function()
  out("setup after the sweep " .. target())
  fresh()
end)
step(0.5, function() SetCameraRotateMode(500, 0, math.pi / 2, 1) end)
step(1.5, function() PanCameraToTimed(300, 300, 0) end)
step(0.5, function()
  out("pan after the sweep " .. target())
  fresh()
end)
step(0.5, function() SetCameraRotateMode(500, 0, math.pi / 2, 1) end)
step(0.5, function() SetCameraTargetController(u, 0, 0, false) end)
step(0.5, function() out("follow during the sweep 0.5s " .. target()) end)
step(1, function()
  out("follow during the sweep 1.5s " .. target())
  fresh()
end)
step(0.5, function() SetCameraRotateMode(500, 0, math.pi / 2, 1) end)
step(0.5, function()
  StopCamera()
  out("stopped during the sweep now " .. target())
end)
step(1, function()
  out("stopped during the sweep 1s " .. target())
  fresh()
end)
step(0.5, function() PanCameraToTimedWithZ(500, 500, 300, 0.5) end)
step(1, function()
  out("pan with z " .. target())
  ResetToGameCamera(0)
end)
step(0.5, function()
  out("pan with z reset " .. target())
  PanCameraToTimedWithZ(0, 0, 300, 0.5)
end)
step(1, function() SetCameraTargetController(u, 0, 0, false) end)
step(0.5, function()
  out("pan with z follow " .. target())
  SetCameraPosition(0, 0)
end)
step(0.5, function() PanCameraToTimedWithZ(1000, 0, 410, 2) end)
step(1, function()
  StopCamera()
  out("pan with z stopped now " .. target())
end)
step(1, function()
  out("pan with z stopped 1s " .. target())
  fresh()
end)
step(0.5, function()
  CameraSetFocalDistance(500)
  CameraSetDepthOfFieldScale(2)
  out("depth of field now " .. field(11) .. " " .. field(12))
end)
step(0.5, function()
  out("depth of field 0.5s " .. field(11) .. " " .. field(12))
  CameraSetSmoothingFactor(1)
  PanCameraTo(1200, 0)
end)
step(0.1, function() reads[#reads + 1] = target() end)
step(0.2, function() reads[#reads + 1] = target() end)
step(0.7, function()
  reads[#reads + 1] = target()
  out("smoothed pan " .. table.concat(reads, ", "))
  CameraSetSmoothingFactor(0)
  SetCameraPosition(0, 0)
end)
step(0.5, function()
  blocker = Rect(200, -200, 600, 200)
  AddCameraBlocker(blocker)
  SetCameraPosition(400, 0)
end)
step(0.5, function()
  out("blocker position " .. target())
  SetCameraPosition(0, 0)
end)
step(0.5, function() PanCameraToTimed(1000, 0, 1) end)
step(1.5, function()
  out("blocker pan " .. target())
  EnableCameraBlocker(blocker, false)
  SetCameraPosition(400, 0)
end)
step(0.5, function()
  out("blocker off " .. target())
  SetCameraPosition(0, 0)
end)
step(0.5, function()
  SetCinematicCamera("Objects\\CinematicCameras\\CameraZoomOut.mdx")
  out("cinematic now " .. target() .. " eye " .. eye())
end)
step(0.5, function()
  out("cinematic 0.5s " .. target() .. " eye " .. eye())
  out("cinematic fields " .. fields())
end)
step(2, function()
  out("cinematic 2.5s " .. target() .. " eye " .. eye())
  ResetToGameCamera(0)
end)
step(0.5, function() out("cinematic reset " .. target() .. " eye " .. eye()) end)
run(1)

-- The natives' argument checks and Lua's error messages: each call in pcall, its result or its error as the game gives
-- it. A call made straight from pcall has no Lua caller, so its error has no position; one inside a function of the
-- script names the line.
local function show(v)
  if type(v) == "userdata" or type(v) == "table" then return (tostring(v):match("^[%a_]+")) end
  return tostring(v)
end
local function try(label, f, ...)
  local ok, v = pcall(f, ...)
  out(label .. " " .. (ok and ("ok " .. show(v)) or ("error " .. show(v))))
end

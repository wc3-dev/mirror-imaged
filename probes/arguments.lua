local function flag(label, ...)
  local tt = CreateTrigger()
  local ok, err = pcall(TriggerWaitOnSleeps, tt, ...)
  out("boolean " .. label .. " " .. (ok and tostring(IsTriggerWaitOnSleeps(tt)) or ("error " .. tostring(err))))
end

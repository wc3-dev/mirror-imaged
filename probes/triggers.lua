-- Triggers, conditions, threads and waits: what runs, in which order and thread, and when a wait ends. Each line
-- starts with what it shows; times are game seconds from a clock timer started first, to 4 places. Each part runs in
-- its own timer callback, so a part that never ends loses only its own lines.
local clock = CreateTimer()
TimerStart(clock, 1000.0, false, nil)
local function now() return string.format("%.4f", TimerGetElapsed(clock)) end
local function id(h) return h == nil and "nil" or tostring(GetHandleId(h)) end
local function where() return tostring(coroutine.isyieldable()) .. " " .. tostring(select(2, coroutine.running())) end
local log = {}
local function cond(name, value) return Condition(function() log[#log + 1] = name return value end) end
local function flush(label) out(label .. " " .. table.concat(log, ",")) log = {} end
local function part(at, label, f)
  TimerStart(CreateTimer(), at, false, function()
    out(label)
    local ok, err = pcall(f)
    if not ok then out(label .. " error " .. tostring(err)) end
  end)
end
local periodic, count = CreateTrigger(), 0

TimerStart(CreateTimer(), 9.0, false, guard(function()
  flush("late")
  out("at end " .. tostring(MirrorProbeVar) .. " " .. count .. " " .. GetTriggerEvalCount(periodic) .. " " .. GetTriggerExecCount(periodic))
  done()
end))

out("timer thread " .. where() .. " trig " .. id(GetTriggeringTrigger()) .. " event " .. id(GetTriggerEventId()))

part(0.1, "basics", function()
  local t = CreateTrigger()
  out("new " .. tostring(IsTriggerEnabled(t)) .. " " .. tostring(IsTriggerWaitOnSleeps(t)) .. " " .. GetTriggerEvalCount(t) .. " " .. GetTriggerExecCount(t))
  out("evaluate empty " .. tostring(TriggerEvaluate(t)) .. " " .. GetTriggerEvalCount(t) .. " " .. GetTriggerExecCount(t))
  TriggerExecute(t)
  out("execute empty " .. GetTriggerEvalCount(t) .. " " .. GetTriggerExecCount(t))
  ResetTrigger(t)
  out("reset " .. GetTriggerEvalCount(t) .. " " .. GetTriggerExecCount(t))
end)

part(0.2, "conditions", function()
  local c = CreateTrigger()
  TriggerAddCondition(c, cond("a", false))
  TriggerAddCondition(c, cond("b", true))
  TriggerAddCondition(c, Condition(function() log[#log + 1] = "e" error("raised") end))
  TriggerAddCondition(c, cond("d", true))
  out("conditions " .. tostring(TriggerEvaluate(c)))
  flush("ran")
  for _, v in ipairs({"nothing", "nil", "zero", "one", "empty", "true"}) do
    local value = ({zero = 0, one = 1, empty = "", ["true"] = true})[v]
    local single = CreateTrigger()
    TriggerAddCondition(single, Condition(function() if v ~= "nothing" then return value end end))
    log[#log + 1] = v .. "=" .. tostring(TriggerEvaluate(single))
  end
  flush("values")
end)

part(0.3, "boolexprs", function()
  local f = function() return true end
  out("handles " .. tostring(Condition(f) == Condition(f)) .. " " .. id(Condition(nil)) .. " " .. id(Filter(nil)) .. " " .. id(And(nil, nil)) .. " " .. id(Not(nil)))
  local b = CreateTrigger()
  TriggerAddCondition(b, And(cond("f1", false), cond("x1", true)))
  TriggerAddCondition(b, Or(cond("t2", true), cond("x2", true)))
  TriggerAddCondition(b, Not(cond("t3", true)))
  TriggerAddCondition(b, And(cond("t4", true), nil))
  TriggerAddCondition(b, Or(nil, cond("f5", false)))
  out("boolexpr " .. tostring(TriggerEvaluate(b)))
  flush("ran")
  local n1, n2, n3, n4 = CreateTrigger(), CreateTrigger(), CreateTrigger(), CreateTrigger()
  TriggerAddCondition(n1, And(nil, nil))
  TriggerAddCondition(n2, Not(nil))
  TriggerAddCondition(n3, nil)
  TriggerAddCondition(n4, Filter(function() return false end))
  out("nil operands " .. tostring(TriggerEvaluate(n1)) .. " " .. tostring(TriggerEvaluate(n2)) .. " " .. tostring(TriggerEvaluate(n3)) .. " " .. tostring(TriggerEvaluate(n4)))
  local d = CreateTrigger()
  local dc = cond("destroyed", true)
  TriggerAddCondition(d, dc)
  DestroyCondition(dc)
  local removed = TriggerAddCondition(d, cond("removed", false))
  TriggerRemoveCondition(d, removed)
  out("destroyed condition " .. tostring(TriggerEvaluate(d)))
  flush("ran")
end)

part(0.4, "actions", function()
  local a = CreateTrigger()
  local first
  first = TriggerAddAction(a, function() log[#log + 1] = "a1" TriggerRemoveAction(a, first) end)
  TriggerAddAction(a, function() log[#log + 1] = "a2 " .. GetTriggerExecCount(a) error("raised") end)
  TriggerAddAction(a, function() log[#log + 1] = "a3" end)
  TriggerExecute(a)
  TriggerExecute(a)
  flush("ran")
  DisableTrigger(a)
  TriggerExecute(a)
  TriggerAddCondition(a, cond("disabled condition", true))
  out("disabled " .. tostring(IsTriggerEnabled(a)) .. " " .. tostring(TriggerEvaluate(a)) .. " " .. GetTriggerExecCount(a))
  flush("ran")
  local inner = CreateTrigger()
  TriggerAddAction(inner, function() log[#log + 1] = "inner " .. tostring(GetTriggeringTrigger() == inner) end)
  local outer = CreateTrigger()
  TriggerAddAction(outer, function()
    log[#log + 1] = "outer " .. where() .. " " .. tostring(GetTriggeringTrigger() == outer) .. " event " .. id(GetTriggerEventId())
    TriggerExecute(inner)
    log[#log + 1] = "back " .. tostring(GetTriggeringTrigger() == outer)
  end)
  TriggerExecute(outer)
  flush("nested")
end)

part(0.5, "condition thread", function()
  local x = CreateTrigger()
  TriggerAddCondition(x, Condition(function()
    out("in condition " .. where() .. " " .. tostring(GetTriggeringTrigger() == x) .. " " .. GetTriggerEvalCount(x))
    local ok, err = pcall(TriggerSleepAction, 0.1)
    out("condition sleep " .. tostring(ok) .. " " .. tostring(err) .. " " .. now())
    return true
  end))
  out("condition evaluated " .. tostring(TriggerEvaluate(x)) .. " " .. now())
end)

part(0.6, "waits", function()
  local w = CreateTrigger()
  TriggerAddAction(w, function()
    out("w start " .. now() .. " " .. where())
    TriggerSleepAction(1)
    out("w 1 " .. now() .. " " .. tostring(GetTriggeringTrigger() == w))
    TriggerSleepAction(0)
    out("w 0 " .. now())
    TriggerSleepAction(0.05)
    out("w 0.05 " .. now())
    TriggerSleepAction(0.33)
    out("w 0.33 " .. now())
    TriggerSleepAction(-1)
    out("w -1 " .. now())
    local ok, err = pcall(function() TriggerSleepAction(0.5) error("after") end)
    out("w pcall " .. now() .. " " .. tostring(ok) .. " " .. tostring(err))
    PolledWait(1)
    out("w polled " .. now())
  end)
  TriggerAddAction(w, function() out("w second action " .. now()) end)
  out("w before " .. now())
  TriggerExecute(w)
  out("w after execute " .. now())
end)

part(0.7, "wait in a coroutine", function()
  local y = CreateTrigger()
  TriggerAddAction(y, function()
    local ok, err = pcall(function()
      coroutine.wrap(function() TriggerSleepAction(0.2) out("wrapped resumed " .. now()) end)()
    end)
    out("in a coroutine " .. now() .. " " .. tostring(ok) .. " " .. tostring(err))
  end)
  TriggerExecute(y)
end)

part(0.8, "execute wait", function()
  local slow = CreateTrigger()
  TriggerAddAction(slow, function() TriggerSleepAction(0.5) out("slow done " .. now()) end)
  local waiter = CreateTrigger()
  TriggerAddAction(waiter, function()
    out("waiter start " .. now())
    TriggerExecuteWait(slow)
    out("waiter after " .. now())
  end)
  TriggerExecute(waiter)
  out("waiter left " .. now())
end)

part(0.9, "execute func", function()
  function MirrorProbeFunc()
    out("func " .. where() .. " " .. now() .. " trig " .. id(GetTriggeringTrigger()))
    TriggerSleepAction(0.25)
    out("func after " .. now())
  end
  ExecuteFunc("MirrorProbeFunc")
  out("after ExecuteFunc " .. now())
end)

part(1.0, "timer events", function()
  TriggerRegisterTimerEvent(periodic, 0.5, true)
  TriggerAddAction(periodic, function()
    count = count + 1
    if count <= 3 then
      local e = GetTriggerEventId()
      out("periodic " .. now() .. " " .. id(e) .. " " .. tostring(e == EVENT_GAME_TIMER_EXPIRED) .. " " .. id(GetExpiredTimer()) .. " " .. GetTriggerEvalCount(periodic) .. " " .. GetTriggerExecCount(periodic))
    end
    if count == 2 then
      DisableTrigger(periodic)
      TimerStart(CreateTimer(), 1.0, false, function() out("enable " .. now()) EnableTrigger(periodic) end)
    end
  end)
  local zero = CreateTrigger()
  TriggerRegisterTimerEvent(zero, 0, false)
  TriggerAddAction(zero, function() out("zero event " .. now()) end)
  local gated = CreateTrigger()
  TriggerRegisterTimerEvent(gated, 0.25, false)
  TriggerAddCondition(gated, Condition(function()
    out("gated condition " .. now() .. " " .. where() .. " " .. tostring(GetTriggeringTrigger() == gated) .. " " .. id(GetTriggerEventId()))
    return false
  end))
  TriggerAddAction(gated, function() out("gated action") end)
  local tm = CreateTimer()
  local x = CreateTrigger()
  TriggerRegisterTimerExpireEvent(x, tm)
  TriggerAddAction(x, function() out("expire trigger " .. now() .. " " .. tostring(GetExpiredTimer() == tm) .. " " .. id(GetTriggerEventId())) end)
  TimerStart(tm, 0.75, false, function() out("expire callback " .. now() .. " " .. where()) end)
end)

part(1.1, "variable", function()
  MirrorProbeVar = 0
  local v = CreateTrigger()
  TriggerRegisterVariableEvent(v, "MirrorProbeVar", GREATER_THAN, 5)
  TriggerAddAction(v, function() out("variable " .. now() .. " " .. tostring(MirrorProbeVar) .. " " .. id(GetTriggerEventId())) end)
  MirrorProbeVar = 10
  out("variable set " .. now())
end)

part(1.2, "game state", function()
  local g = CreateTrigger()
  TriggerRegisterGameStateEvent(g, GAME_STATE_DIVINE_INTERVENTION, EQUAL, 1)
  TriggerAddAction(g, function() out("state " .. now() .. " " .. id(GetEventGameState()) .. " " .. id(GetTriggerEventId())) end)
  SetIntegerGameState(GAME_STATE_DIVINE_INTERVENTION, 1)
  out("state set " .. now() .. " " .. GetIntegerGameState(GAME_STATE_DIVINE_INTERVENTION))
end)


-- The camera following a footman: SetCameraTargetController and SetCameraOrientController, and what ends them. Each
-- step runs after the wait before it.
local function F(x) return string.format("%.4f", x) end
local function target() return F(GetCameraTargetPositionX()) .. " " .. F(GetCameraTargetPositionY()) .. " " .. F(GetCameraTargetPositionZ()) end
local function field(i) return F(GetCameraField(ConvertCameraField(i))) end

local steps = {}
local function step(wait, f) steps[#steps + 1] = {wait, f} end
local function run(i)
  if i > #steps then done() return end
  TimerStart(CreateTimer(), steps[i][1], false, guard(function() steps[i][2]() run(i + 1) end))
end

SetCameraBounds(-2000, -2000, 2000, 2000, -2000, 2000, 2000, -2000)
local u = CreateUnit(Player(0), FourCC("hfoo"), 200, 100, 90)
SetCameraTargetController(u, 100, 50, false)
out("follow now " .. target())
step(0, function() out("follow 0s " .. target()) end)
step(0.5, function()
  out("follow 0.5s " .. target())
  SetUnitX(u, 600)
  SetUnitY(u, -300)
  out("unit moved now " .. target())
end)
step(0.5, function()
  out("unit moved 0.5s " .. target())
  SetCameraOrientController(u, 0, 0)
end)
step(0.5, function()
  out("orient " .. target() .. " rotation " .. field(5))
  BlzSetUnitFacingEx(u, 0)
end)
step(0.5, function()
  out("orient faced 0 " .. target() .. " rotation " .. field(5))
  PanCameraToTimed(0, 0, 0)
end)
step(0.5, function()
  out("after pan " .. target() .. " rotation " .. field(5))
  SetUnitX(u, -500)
end)
step(0.5, function()
  out("after pan unit moved " .. target())
  SetCameraTargetController(u, 0, 0, false)
end)
step(0.5, function()
  out("follow again " .. target())
  ResetToGameCamera(0)
end)
step(0.5, function()
  SetUnitX(u, 500)
end)
step(0.5, function()
  out("after reset unit moved " .. target() .. " rotation " .. field(5))
  SetCameraTargetController(u, 0, 0, true)
end)
step(0.5, function()
  out("inherit " .. target() .. " rotation " .. field(5))
  BlzSetUnitFacingEx(u, 180)
end)
step(0.5, function()
  out("inherit faced 180 " .. target() .. " rotation " .. field(5))
  SetCameraPosition(GetCameraTargetPositionX(), GetCameraTargetPositionY())
end)
step(0.5, function()
  SetUnitX(u, 0)
end)
step(0.5, function()
  out("after position at target " .. target())
  SetCameraTargetController(u, 0, 0, false)
end)
step(0.5, function()
  RemoveUnit(u)
end)
step(0.5, function()
  out("removed " .. target())
end)
run(1)

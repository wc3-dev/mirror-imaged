-- The hashtable natives (W1-3): what each load and check gives after the saves before it, a float with its bits.
local function show(v)
    if v == nil then return 'nil' end
    local t = math.type(v)
    if t == 'float' then return 'f ' .. string.format('%08x', string.unpack('<i4', string.pack('<f', v))) end
    if t == 'integer' then return 'i ' .. v end
    if type(v) == 'string' then return 's "' .. v .. '"' end
    if type(v) == 'boolean' then return tostring(v) end
    return tostring(v):match('^[^:]+')
end
local function case(name, f, ...)
    local ok, v = pcall(f, ...)
    out(name .. ' = ' .. (ok and show(v) or 'error ' .. tostring(v)))
end
local function is(name, a, b)
    out(name .. ' = ' .. tostring(a == b))
end


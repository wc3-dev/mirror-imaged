  end
  out("sleep creep state " .. GetPlayerState(na, PLAYER_STATE_NO_CREEP_SLEEP))
  read("made")
  TimerStart(CreateTimer(), 0, false, function() read("0s") end)
  TimerStart(CreateTimer(), 0.5, false, function() read("0.5s") end)
  TimerStart(CreateTimer(), 2, false, function()
    read("2s")
    UnitWakeUp(all.woken)
    read("woken")
  end)
  TimerStart(CreateTimer(), 3, false, function()
    read("3s")
    UnitAddSleep(all.nosleep, true)
    UnitAddSleepPerm(all.perm, false)
    read("changed")
  end)
  TimerStart(CreateTimer(), 4.5, false, function()
    read("4.5s")
    SetFloatGameState(GAME_STATE_TIME_OF_DAY, 12)
    read("noon")
  end)
  TimerStart(CreateTimer(), 5, false, function() read("noon 0.5s") end)
  TimerStart(CreateTimer(), 7, false, function()
    read("noon 2.5s")
    all.late = make("nmrl", na, 1500, 1500)
    order[#order + 1] = "late"
    read("late made")
    SetFloatGameState(GAME_STATE_TIME_OF_DAY, 23)

part(1.0, "orders", function()
  local depth, names = 0, {}
  local o = CreateTrigger()
  for _, e in ipairs({ EVENT_PLAYER_UNIT_ISSUED_ORDER, EVENT_PLAYER_UNIT_ISSUED_POINT_ORDER, EVENT_PLAYER_UNIT_ISSUED_TARGET_ORDER, EVENT_PLAYER_UNIT_DEATH }) do
    TriggerRegisterPlayerUnitEvent(o, Player(0), e, nil)
    TriggerRegisterPlayerUnitEvent(o, Player(1), e, nil)
  end
  TriggerAddAction(o, function()
    depth = depth + 1
    local u = GetTriggerUnit()
    out(string.rep(">", depth) .. " " .. (names[u] or "?") .. " " .. GetHandleId(GetTriggerEventId()) .. " " .. GetIssuedOrderId() .. " "
      .. pid(GetTriggerPlayer()) .. " dead " .. tf(IsUnitType(u, UNIT_TYPE_DEAD)) .. " " .. GetWidgetLife(u) .. " " .. tf(GetUnitTypeId(u) ~= 0)
      .. " paused " .. tf(IsUnitPaused(u)) .. " " .. now())
    depth = depth - 1
  end)
  local function unit(name, id)
    local u = make(id)
    names[u] = name
    for _, e in ipairs({ EVENT_UNIT_ISSUED_ORDER, EVENT_UNIT_ISSUED_POINT_ORDER, EVENT_UNIT_ISSUED_TARGET_ORDER, EVENT_UNIT_DEATH }) do
      TriggerRegisterUnitEvent(o, u, e)
    end
    return u
  end
  local f, r = unit("f", "hfoo"), unit("r", "hrif")
  out("pause f")
  PauseUnit(f, true)
  out("pause f again")
  PauseUnit(f, true)
  out("unpause f")
  PauseUnit(f, false)
  out("unpause f again")
  PauseUnit(f, false)
  out("pause r")
  PauseUnit(r, true)
  out("unpause r")
  PauseUnit(r, false)
  local f2 = unit("f2", "hfoo")
  out("kill f2")
  KillUnit(f2)
  out("kill f2 again")
  KillUnit(f2)
  out("pause dead f2")
  PauseUnit(f2, true)
  PauseUnit(f2, false)
  local f3 = unit("f3", "hfoo")
  out("remove f3")
  RemoveUnit(f3)
  out("remove f3 again")
  RemoveUnit(f3)
  local f4 = unit("f4", "hfoo")
  out("kill f4")
  KillUnit(f4)
  out("remove dead f4")
  RemoveUnit(f4)
  local f5 = unit("f5", "hfoo")
  SetUnitExploded(f5, true)
  out("explode f5")
  KillUnit(f5)
  local f6 = unit("f6", "hfoo")
  out("pause and remove f6")
  PauseUnit(f6, true)
  RemoveUnit(f6)
  local f7 = unit("f7", "hfoo")
  out("life 0 f7")
  SetWidgetLife(f7, 0)
  local r2 = unit("r2", "hrif")
  out("kill r2")
  KillUnit(r2)
  local f8 = unit("f8", "hfoo")
  PauseUnit(f8, true)
  out("give paused f8")
  SetUnitOwner(f8, Player(1), false)
  local h = unit("h", "Hpal")
  out("pause h")
  PauseUnit(h, true)
  PauseUnit(h, false)
  out("corpse")

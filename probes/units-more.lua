-- The rest of the units (W2-10), on the probe map (custom_v1's data): names (UnitId, UnitId2String, CreateUnitByName),
-- IsUnit, illusions, selectable, the alarm, food, the unit counts, timed life, the unit state and filter events, the
-- order events of PauseUnit, KillUnit, RemoveUnit and SetUnitOwner (undefend 852056, stunned 851973),
-- SetPlayerUnitsOwner, rescue, and sleep at night (the game starts at midnight). Each unit of Player 0 is made on a spot
-- of its own in a grid at the bottom left; the creeps stand far from it at the top right.
-- Every player passive to every other but the creeps, so no units fight
for i = 0, 15 do
  for j = 0, 15 do SetPlayerAlliance(Player(i), Player(j), ALLIANCE_PASSIVE, true) end
end
local clock = CreateTimer()
TimerStart(clock, 1000.0, false, nil)
local function now() return string.format("%.2f", TimerGetElapsed(clock)) end
local function show(v) return v == nil and "nil" or tostring(v) end
local function pid(p) return p == nil and "nil" or tostring(GetPlayerId(p)) end
local function tf(v) return v and "t" or "f" end
local function code(i) return i == 0 and "0" or string.pack(">i4", i) end
local spot = 0
local function place()
  spot = spot % 100 + 1
  return (spot % 10) * 200 - 1900, (spot // 10) * 200 - 1900
end
local function make(id, p, x, y)
  if not x then x, y = place() end
  return CreateUnit(p or Player(0), FourCC(id), x, y, 0)
end
local function part(at, label, f)
  TimerStart(CreateTimer(), at, false, function()
    out(label)
    local ok, err = pcall(f)
    if not ok then out(label .. " error " .. tostring(err)) end
  end)
end


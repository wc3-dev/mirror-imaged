part(2.0, "sleep", function()
  local na = Player(PLAYER_NEUTRAL_AGGRESSIVE)
  local all = {
    m = make("nmrl", na, 1900, 1900),
    fo = make("hfoo", na, 1900, 1100),
    mine = make("nmrl", Player(0), -200, 1900),
    woken = make("nmrl", na, 1900, 1500),
    nosleep = make("nmrl", na, 1500, 1900),
    perm = make("nmrl", na, 1100, 1900),
  }
  local order = { "m", "fo", "mine", "woken", "nosleep", "perm" }
  UnitAddSleep(all.nosleep, false)
  UnitAddSleepPerm(all.perm, true)
  local function read(label)
    local parts = {}
    for _, k in ipairs(order) do
      local u = all[k]
      parts[#parts + 1] = k .. " " .. tf(UnitIsSleeping(u)) .. tf(IsUnitType(u, UNIT_TYPE_SLEEPING)) .. tf(UnitCanSleep(u)) .. tf(UnitCanSleepPerm(u))
    end

part(0.4, "timed", function()
  local function watch(label, u)
    local t = CreateTrigger()
    TriggerRegisterUnitEvent(t, u, EVENT_UNIT_DEATH)
    TriggerRegisterUnitEvent(t, u, EVENT_UNIT_DECAY)
    TriggerAddAction(t, function()
      out("timed " .. label .. " " .. (GetTriggerEventId() == EVENT_UNIT_DEATH and "death" or "decay") .. " " .. now() .. " killer "
        .. show(GetKillingUnit()) .. " life " .. GetWidgetLife(u))
    end)
    return u
  end
  local a = watch("a", make("hfoo"))
  UnitApplyTimedLife(a, FourCC("BTLF"), 1)
  out("timed summoned " .. tf(IsUnitType(a, UNIT_TYPE_SUMMONED)) .. tf(IsUnitType(make("hfoo"), UNIT_TYPE_SUMMONED)))
  local c = watch("shorter", make("hfoo"))
  UnitApplyTimedLife(c, FourCC("BTLF"), 3)
  UnitApplyTimedLife(c, FourCC("BTLF"), 1)
  local d = watch("longer", make("hfoo"))
  UnitApplyTimedLife(d, FourCC("BTLF"), 1)
  UnitApplyTimedLife(d, FourCC("BTLF"), 2)
  local e = watch("paused", make("hfoo"))
  UnitApplyTimedLife(e, FourCC("BTLF"), 1)
  local f = watch("cancelled", make("hfoo"))
  UnitApplyTimedLife(f, FourCC("BTLF"), 1)
  local g = watch("zero", make("hfoo"))
  UnitApplyTimedLife(g, FourCC("BTLF"), 0)
  local h = watch("negative", make("hfoo"))
  UnitApplyTimedLife(h, FourCC("BTLF"), -1)
  local k = watch("hero", make("Hpal"))
  UnitApplyTimedLife(k, FourCC("BTLF"), 1)
  local m = watch("buff", make("hfoo"))
  UnitApplyTimedLife(m, FourCC("BHwe"), 1)
  local n = watch("dead", make("hfoo"))
  KillUnit(n)
  UnitApplyTimedLife(n, FourCC("BTLF"), 1)
  local o = watch("nobuff", make("hfoo"))
  UnitApplyTimedLife(o, 0, 1)
  local s = watch("unpaused", make("hfoo"))
  UnitPauseTimedLife(s, true)
  UnitApplyTimedLife(s, FourCC("BTLF"), 1)
  out("timed made " .. now() .. " " .. tf(UnitAlive(g)) .. tf(UnitAlive(h)))
  TimerStart(CreateTimer(), 0.5, false, function()
    UnitPauseTimedLife(e, true)
    BlzUnitCancelTimedLife(f)
    out("timed paused " .. now())
  end)
  TimerStart(CreateTimer(), 2.0, false, function()
    UnitPauseTimedLife(e, false)
    out("timed resumed " .. now() .. " " .. tf(UnitAlive(e)) .. tf(UnitAlive(f)))
  end)
  TimerStart(CreateTimer(), 5.0, false, function() out("timed end " .. tf(UnitAlive(e)) .. tf(UnitAlive(f)) .. tf(UnitAlive(o)) .. tf(UnitAlive(s))) end)
end)


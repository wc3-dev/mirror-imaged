-- Triggers, second part: removal and destruction of conditions, nil boolexprs, counts, TriggerExecuteWait with
-- TriggerWaitOnSleeps, event ids and their equality, game state events, timer event timeouts and order, wait lengths,
-- and the context a nested execution inherits.
local clock = CreateTimer()
TimerStart(clock, 1000.0, false, nil)
local function now() return string.format("%.4f", TimerGetElapsed(clock)) end
local function id(h) return h == nil and "nil" or tostring(GetHandleId(h)) end
local function kind(h) return h == nil and "nil" or tostring(h):match("^[%a_]+") end
local log = {}
local function cond(name, value) return Condition(function() log[#log + 1] = name return value end) end
local function flush(label) out(label .. " " .. table.concat(log, ",")) log = {} end
local function part(at, label, f)
  TimerStart(CreateTimer(), at, false, function()
    out(label)
    local ok, err = pcall(f)
    if not ok then out(label .. " error " .. tostring(err)) end
  end)
end
local function evaluate(...)
  local t = CreateTrigger()
  for _, c in ipairs({...}) do TriggerAddCondition(t, c) end
  return tostring(TriggerEvaluate(t))
end

TimerStart(CreateTimer(), 9.0, false, guard(function()
  flush("late")
  done()
end))

part(0.1, "removal", function()
  local t = CreateTrigger()
  local tc = TriggerAddCondition(t, cond("r1", false))
  TriggerRemoveCondition(t, tc)
  out("removed only " .. tostring(TriggerEvaluate(t)))
  flush("ran")
  t = CreateTrigger()
  local first = TriggerAddCondition(t, cond("first", true))
  TriggerAddCondition(t, cond("second", true))
  TriggerRemoveCondition(t, first)
  out("removed first " .. tostring(TriggerEvaluate(t)))
  flush("ran")
  t = CreateTrigger()
  TriggerAddCondition(t, cond("c1", true))
  local second = TriggerAddCondition(t, cond("c2", false))
  TriggerRemoveCondition(t, second)
  out("removed second " .. tostring(TriggerEvaluate(t)))
  flush("ran")
  t = CreateTrigger()
  TriggerAddCondition(t, cond("k1", true))
  TriggerClearConditions(t)
  out("cleared " .. tostring(TriggerEvaluate(t)))
  flush("ran")
  local dc = cond("destroyed", true)
  t = CreateTrigger()
  TriggerAddCondition(t, dc)
  DestroyCondition(dc)
  out("destroyed only " .. tostring(TriggerEvaluate(t)))
  flush("ran")
  local df = Filter(function() log[#log + 1] = "filter" return true end)
  t = CreateTrigger()
  TriggerAddCondition(t, df)
  DestroyFilter(df)
  out("destroyed filter " .. tostring(TriggerEvaluate(t)))
  flush("ran")
  local de = And(cond("and1", true), cond("and2", true))
  t = CreateTrigger()
  TriggerAddCondition(t, de)
  DestroyBoolExpr(de)
  out("destroyed and " .. tostring(TriggerEvaluate(t)))
  flush("ran")
  local inner = cond("inner", true)
  t = CreateTrigger()
  TriggerAddCondition(t, Not(inner))
  DestroyCondition(inner)
  out("destroyed operand " .. tostring(TriggerEvaluate(t)))
  flush("ran")
end)

part(0.2, "nil boolexprs", function()
  local cn, fn = Condition(nil), Filter(nil)
  out("nil handles " .. id(cn) .. " " .. id(Condition(nil)) .. " " .. id(fn) .. " " .. kind(cn) .. " " .. kind(fn) .. " " .. tostring(cn == fn) .. " " .. tostring(rawequal(cn, Condition(nil))))
  out("nil values " .. evaluate(cn) .. " " .. evaluate(Not(cn)) .. " " .. evaluate(And(cond("t", true), nil)) .. " " .. evaluate(And(nil, cond("u", true)))
    .. " " .. evaluate(Or(nil, cond("v", true))) .. " " .. evaluate(Or(cond("w", false), nil)) .. " " .. evaluate(Or(cond("x", true), nil)))
  flush("ran")
  out("values " .. evaluate(Not(cond("a", false))) .. " " .. evaluate(And(cond("b", true), cond("c", true))) .. " " .. evaluate(Or(cond("d", false), cond("e", false))))
  flush("ran")
  out("returns " .. evaluate(Condition(function() return "x" end)) .. " " .. evaluate(Condition(function() return "1" end)) .. " " .. evaluate(Condition(function() return 0.5 end))
    .. " " .. evaluate(Condition(function() return {} end)) .. " " .. evaluate(Condition(function() return -1 end)) .. " " .. evaluate(Condition(function() return false, true end)))
end)

part(0.3, "counts", function()
  local t = CreateTrigger()
  TriggerAddCondition(t, cond("y", true))
  TriggerEvaluate(t)
  local n = CreateTrigger()
  TriggerAddCondition(n, cond("n", false))
  TriggerEvaluate(n)
  out("evaluate counts " .. GetTriggerEvalCount(t) .. " " .. GetTriggerExecCount(t) .. " " .. GetTriggerEvalCount(n) .. " " .. GetTriggerExecCount(n))
  flush("ran")
  local gated = CreateTrigger()
  TriggerAddCondition(gated, cond("gated", false))
  TriggerRegisterTimerEvent(gated, 0.1, false)
  local off = CreateTrigger()
  TriggerAddCondition(off, cond("off", true))
  TriggerAddAction(off, function() log[#log + 1] = "off action" end)
  TriggerRegisterTimerEvent(off, 0.1, false)
  DisableTrigger(off)
  TimerStart(CreateTimer(), 0.2, false, function()
    out("event counts " .. GetTriggerEvalCount(gated) .. " " .. GetTriggerExecCount(gated) .. " " .. GetTriggerEvalCount(off) .. " " .. GetTriggerExecCount(off))
    flush("ran")
  end)
end)

part(0.6, "execute wait", function()
  local slow = CreateTrigger()
  TriggerWaitOnSleeps(slow, true)
  TriggerAddAction(slow, function() TriggerSleepAction(0.5) out("slow done " .. now()) end)
  local waiter = CreateTrigger()
  TriggerAddAction(waiter, function()
    out("waiter start " .. now() .. " " .. tostring(IsTriggerWaitOnSleeps(slow)))
    TriggerExecuteWait(slow)
    out("waiter after " .. now())
    TriggerExecute(slow)
    out("waiter after execute " .. now())
  end)
  TriggerExecute(waiter)
  out("waiter left " .. now())
end)

part(0.7, "event ids", function()
  local e = GetTriggerEventId()
  out("timer callback " .. id(e) .. " " .. kind(e) .. " " .. tostring(e == EVENT_GAME_VICTORY) .. " " .. tostring(rawequal(e, GetTriggerEventId())) .. " " .. tostring(e == GetTriggerEventId()))
  local p = CreateTrigger()
  TriggerRegisterTimerEvent(p, 0.1, false)
  local inner = CreateTrigger()
  TriggerAddAction(inner, function()
    log[#log + 1] = "inner " .. id(GetTriggerEventId()) .. " " .. tostring(GetTriggeringTrigger() == inner)
  end)
  function MirrorProbeFunc()
    log[#log + 1] = "func " .. id(GetTriggerEventId()) .. " " .. tostring(GetTriggeringTrigger() == p)
    TriggerSleepAction(0.2)
    log[#log + 1] = "func after " .. now() .. " " .. tostring(GetTriggeringTrigger() == p)
  end
  TriggerAddAction(p, function()
    local x = GetTriggerEventId()
    out("event " .. id(x) .. " " .. kind(x) .. " " .. kind(EVENT_GAME_TIMER_EXPIRED) .. " " .. tostring(x == EVENT_GAME_TIMER_EXPIRED) .. " " .. tostring(rawequal(x, EVENT_GAME_TIMER_EXPIRED))
      .. " " .. tostring(x == ConvertGameEvent(4)) .. " " .. tostring(x == ConvertLimitOp(4)) .. " " .. tostring(x == ConvertPlayerColor(4)))
    TriggerExecute(inner)
    ExecuteFunc("MirrorProbeFunc")
    flush("nested")
  end)
end)

part(1.0, "game states", function()
  local g = CreateTrigger()
  TriggerRegisterGameStateEvent(g, GAME_STATE_DIVINE_INTERVENTION, GREATER_THAN, 1)
  TriggerAddAction(g, function()
    local e = GetTriggerEventId()
    log[#log + 1] = GetIntegerGameState(GAME_STATE_DIVINE_INTERVENTION) .. " " .. id(e) .. " " .. tostring(e == EVENT_GAME_STATE_LIMIT) .. " " .. kind(GetEventGameState())
      .. " " .. tostring(GetEventGameState() == GAME_STATE_DIVINE_INTERVENTION)
  end)
  for _, value in ipairs({2, 2, 0, 3, 1, 5}) do SetIntegerGameState(GAME_STATE_DIVINE_INTERVENTION, value) end
  flush("divine")
  local d = CreateTrigger()
  TriggerRegisterGameStateEvent(d, GAME_STATE_DISCONNECTED, NOT_EQUAL, 0)
  TriggerAddAction(d, function() log[#log + 1] = "disconnected " .. GetIntegerGameState(GAME_STATE_DISCONNECTED) end)
  SetIntegerGameState(GAME_STATE_DISCONNECTED, 2)
  SetIntegerGameState(GAME_STATE_DISCONNECTED, 0)
  out("disconnected now " .. GetIntegerGameState(GAME_STATE_DISCONNECTED))
  flush("ran")
  local tod = CreateTrigger()
  TriggerRegisterGameStateEvent(tod, GAME_STATE_TIME_OF_DAY, EQUAL, 6)
  TriggerAddAction(tod, function()
    local e = GetTriggerEventId()
    log[#log + 1] = "time " .. id(e) .. " " .. tostring(e == EVENT_GAME_STATE_LIMIT) .. " " .. id(GetEventGameState()) .. " " .. tostring(GetEventGameState() == GAME_STATE_TIME_OF_DAY)
  end)
  SetFloatGameState(GAME_STATE_TIME_OF_DAY, 6)
  flush("time of day")
end)

part(1.5, "timer events", function()
  for _, timeout in ipairs({0.02, 0.01, 0.005, 0.001, 0}) do
    local t = CreateTrigger()
    TriggerRegisterTimerEvent(t, timeout, false)
    TriggerAddAction(t, function() log[#log + 1] = timeout .. "@" .. now() end)
  end
  local z, count = CreateTrigger(), 0
  TriggerRegisterTimerEvent(z, 0, true)
  TriggerAddAction(z, function() count = count + 1 end)
  TimerStart(CreateTimer(), 0.1, false, function() DisableTrigger(z) out("periodic zero in 0.1 s " .. count) end)
  local a, b = CreateTrigger(), CreateTrigger()
  TriggerRegisterTimerEvent(b, 0.05, false)
  TriggerRegisterTimerEvent(a, 0.05, false)
  TriggerRegisterTimerEvent(b, 0.05, false)
  TriggerAddAction(a, function() log[#log + 1] = "a" end)
  TriggerAddAction(b, function() log[#log + 1] = "b" end)
  local tm = CreateTimer()
  local x1, x2 = CreateTrigger(), CreateTrigger()
  TriggerRegisterTimerExpireEvent(x2, tm)
  TriggerRegisterTimerExpireEvent(x1, tm)
  TriggerRegisterTimerExpireEvent(x2, tm)
  TriggerAddAction(x1, function() log[#log + 1] = "x1" end)
  TriggerAddAction(x2, function() log[#log + 1] = "x2" end)
  TimerStart(tm, 0.06, true, function() log[#log + 1] = "callback" if #log > 12 then PauseTimer(tm) end end)
  TimerStart(CreateTimer(), 0.2, false, function() flush("timer events") end)
end)

part(2.0, "wait lengths", function()
  local function sleeper(label, times)
    local t = CreateTrigger()
    TriggerAddAction(t, function()
      local marks = {now()}
      for _, s in ipairs(times) do TriggerSleepAction(s) marks[#marks + 1] = now() end
      out(label .. " " .. table.concat(marks, " "))
    end)
    return t
  end
  TriggerExecute(sleeper("tenths", {0.1, 0.1, 0.1, 0.15, 0.2, 0.25, 0.5, 0.55, 0.01, 0.09, 0.11}))
  TimerStart(CreateTimer(), 0.033, false, function() TriggerExecute(sleeper("off grid", {0.1, 0.2, 0, 0.5})) end)
  TimerStart(CreateTimer(), 0.25, false, function() TriggerExecute(sleeper("quarter", {0, 0.3, 1})) end)
  TimerStart(CreateTimer(), 0.5, false, function()
    local t = CreateTrigger()
    TriggerAddAction(t, function() local s = now() PolledWait(1) local m = now() PolledWait(0.5) local n = now() PolledWait(3) out("polled " .. s .. " " .. m .. " " .. n .. " " .. now()) end)
    TriggerExecute(t)
  end)
end)

part(2.1, "changes while running", function()
  local t = CreateTrigger()
  TriggerAddAction(t, function()
    log[#log + 1] = "first"
    TriggerAddAction(t, function() log[#log + 1] = "added" end)
  end)
  TriggerAddAction(t, function() log[#log + 1] = "second" TriggerClearActions(t) end)
  TriggerAddAction(t, function() log[#log + 1] = "third" end)
  TriggerExecute(t)
  TriggerExecute(t)
  flush("ran")
  local s = CreateTrigger()
  TriggerAddAction(s, function() log[#log + 1] = "s1" TriggerSleepAction(0.1) log[#log + 1] = "s1 after" end)
  TriggerAddAction(s, function() log[#log + 1] = "s2" end)
  TriggerExecute(s)
  TriggerAddAction(s, function() log[#log + 1] = "s3 added while asleep" end)
end)


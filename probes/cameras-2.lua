-- The local player's camera, second part, inside bounds of 2000 each way: when a position, a pan and a setup applied
-- read back; where the bounds hold the target; each field's limits and angles; fields over time; the eye at another
-- rotation. Each step runs after the wait before it.
local function F(x) return string.format("%.4f", x) end
local function target() return F(GetCameraTargetPositionX()) .. " " .. F(GetCameraTargetPositionY()) .. " " .. F(GetCameraTargetPositionZ()) end
local function eye() return F(GetCameraEyePositionX()) .. " " .. F(GetCameraEyePositionY()) .. " " .. F(GetCameraEyePositionZ()) end
local function field(i) return F(GetCameraField(ConvertCameraField(i))) end
local function set(i, v, d) SetCameraField(ConvertCameraField(i), v, d or 0) end

local steps, applied = {}, nil
local function step(wait, f) steps[#steps + 1] = {wait, f} end
local function run(i)
  if i > #steps then done() return end
  TimerStart(CreateTimer(), steps[i][1], false, guard(function() steps[i][2]() run(i + 1) end))
end

-- A field set to each value in turn, read at once after each.
local function limits(name, i, list)
  local t = {}
  for _, v in ipairs(list) do set(i, v) t[#t + 1] = field(i) end
  out(name .. " " .. table.concat(t, " "))
end

SetCameraBounds(-2000, -2000, 2000, 2000, -2000, 2000, 2000, -2000)
out("start " .. target())
limits("distance", 0, {0, 0.3, 0.5, 1, 100, 100000})
limits("farz", 1, {0, 50, 99.9, 100, 101, 100000})
limits("aoa", 2, {0, 0.0001, 359.9999, 360, 720, -360, -720, 1080})
limits("fov", 3, {0, 10, 19.9, 20, 21, 119, 120, 121, 179, 361})
limits("roll", 4, {360, 361, -1, 1080})
limits("zoffset", 6, {-100000, 100000, 0})
limits("nearz", 7, {0, 5, 15.9, 16, 17, 100, 100000, 16})
limits("zabsolute", 13, {0.5, -1, 0})

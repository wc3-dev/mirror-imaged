-- A unit's resources (W2-10), on the probe map (custom_v1's data): GetResourceAmount of a new gold mine (its Agld's
-- Max Gold, 12500 in the tables), a haunted and an entangled one, a footman and nil; SetResourceAmount and
-- AddResourceAmount at their edges, a mine set to 0, a dead mine, and a footman given gold.
local function show(v) return v == nil and "nil" or tostring(v) end
local np = Player(PLAYER_NEUTRAL_PASSIVE)
local function mine(id, x, y)
  local m = CreateUnit(np, FourCC(id), x, y, 0)
  local t = CreateTrigger()
  TriggerRegisterUnitEvent(t, m, EVENT_UNIT_DEATH)
  TriggerAddAction(t, function() out(id .. " death " .. GetResourceAmount(m)) end)
  return m
end

local m, u, e = mine("ngol", -1200, -1200), mine("ugol", 0, -1200), mine("egol", 1200, -1200)
local f = CreateUnit(Player(0), FourCC("hfoo"), -1200, 1200, 0)
out("new " .. GetResourceAmount(m) .. " " .. GetResourceAmount(u) .. " " .. GetResourceAmount(e) .. " " .. GetResourceAmount(f) .. " "
  .. GetResourceAmount(nil))
SetResourceAmount(m, 5000)
out("set 5000 " .. GetResourceAmount(m))
AddResourceAmount(m, 250)
out("add 250 " .. GetResourceAmount(m))
AddResourceAmount(m, -6000)
out("add -6000 " .. GetResourceAmount(m) .. " " .. tostring(UnitAlive(m)))
SetResourceAmount(m, -5)
out("set -5 " .. GetResourceAmount(m) .. " " .. tostring(UnitAlive(m)))
SetResourceAmount(m, 2147483647)
AddResourceAmount(m, 1)
out("past the most " .. GetResourceAmount(m))
SetResourceAmount(m, 0)
out("set 0 " .. GetResourceAmount(m) .. " " .. tostring(UnitAlive(m)))
SetResourceAmount(f, 100)
AddResourceAmount(f, 5)
out("footman " .. GetResourceAmount(f))
SetResourceAmount(u, 300)
SetResourceAmount(e, 400)
local b = CreateUnit(Player(0), FourCC("hbar"), 1200, 0, 0)
SetResourceAmount(b, 500)
out("haunted " .. GetResourceAmount(u) .. " entangled " .. GetResourceAmount(e) .. " barracks " .. GetResourceAmount(b))
local d = mine("ngol", 1200, 1200)
KillUnit(d)
out("dead " .. GetResourceAmount(d))
SetResourceAmount(d, 70)
out("dead set " .. GetResourceAmount(d))
SetResourceAmount(nil, 5)
AddResourceAmount(nil, 5)
TimerStart(CreateTimer(), 1, false, guard(function()
  out("later " .. GetResourceAmount(m) .. " " .. tostring(UnitAlive(m)) .. " " .. show(GetUnitTypeId(m) ~= 0))
  done()
end))
